package com.java;

public class Datatypes {

	public static void main(String[] args) {
		double d=1000000.57451546;
		int i=(int)d;
		long l=(long)d;
		float f=(float)d;
		System.out.println("Double="+d);
		System.out.println("int="+i);
		System.out.println("Long="+l);
		System.out.println("float="+f);
		

	}

}
